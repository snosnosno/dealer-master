/**
 * 팟 층의 이름.
 *
 * 딜러가 부르는 이름 그대로다 — 메인팟 · 세컨드팟 · 서드팟. **번호가 아니라 이름**인
 * 것이 중요하다: 「사이드팟 2」는 뒤에 오는 금액과 붙어 「24,800」 한 덩어리로 읽히고,
 * 트레이니는 묻지 않은 숫자를 보고 답한다 (이 드릴에서 실제로 겪은 결함이다).
 *
 * 네 층째부터는 이름이 모자란다. 지금 생성기는 세 층까지만 만들지만, 이름이 없다고
 * 화면이 비면 안 되므로 번호로 떨어뜨린다.
 */
const POT_NAMES = ['메인팟', '세컨드팟', '서드팟'] as const

export function potName(potIndex: number): string {
  return POT_NAMES[potIndex] ?? `${potIndex + 1}번째 팟`
}
